export default async function BlogPost({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const decodedSlug = decodeURIComponent(slug);
  const post = blogData[decodedSlug as keyof typeof blogData];

  if (!post) return notFound();

  return (
    <article className="max-w-4xl mx-auto py-16 px-6 text-right" dir="rtl">
      <header className="mb-10 border-b pb-6">
        <h1 className="text-4xl font-extrabold text-blue-900 mb-4 leading-tight">
          {post.title}
        </h1>
        <p className="text-gray-400">📅 {post.date} | بواسطة فريق DocuVat</p>
      </header>
      
      <div className="prose lg:prose-xl max-w-none text-gray-800 leading-relaxed">
        {post.content.split('###').map((section, index) => {
          if (!section.trim()) return null;
          const [title, ...lines] = section.split('\n');
          return (
            <div key={index} className="mt-8">
              <h2 className="text-2xl font-bold text-blue-700 mb-4">{title.trim()}</h2>
              <div className="whitespace-pre-line">
                {lines.join('\n').trim()}
              </div>
            </div>
          );
        })}
      </div>

      {/* Call to Action Box */}
      <div className="mt-16 p-8 bg-gradient-to-r from-blue-600 to-blue-800 rounded-2xl text-white shadow-xl">
        <h3 className="text-2xl font-bold mb-3">لا تترك عملك للصدفة!</h3>
        <p className="text-blue-100 mb-6 text-lg">
          سواء كنت تريد إصدار فواتير ضريبية دقيقة أو أوامر شراء تحميك، DocuVat هو الحل الأمثل لشركتك في الإمارات.
        </p>
        <a href="/" className="inline-block bg-white text-blue-700 px-8 py-3 rounded-xl font-bold text-lg hover:bg-gray-100 transition-all">
          ابدأ الآن مجاناً
        </a>
      </div>
    </article>
  );
}